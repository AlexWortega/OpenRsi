#!/usr/bin/env python3
"""Generation-6 exact audit of the Pro-2 global selector quotient.

The finite instance is the conjunction of all eight three-literal clauses.
Clause c is falsified by global assignment c.  Each clause has all eight
local-pattern selector coordinates; pattern 000 is the illegal label.

The quotient is defined conservatively as Z^64/H, where H is generated by
all seven differences between the eight complete Boolean selector vectors.
Normalization and cross-clause variable consistency are dual equations that
define the harmful affine set, not ambient vectors that can canonically be
added to H.  Quotienting by their entire preserving kernel would annihilate
all harmful consistent moves by definition.

For every complete Boolean reference, this verifier exhausts every integral
signed-selector deviation of squared norm at most 12 that preserves clause
normalization and global variable consistency and removes every illegal
selector.  It tests exact zero in Z^64/H and zero modulo 2.  The latter is the
modular-multiple bypass test for an explicit repeated binary quotient code.

A full-rank triangular lattice basis and target are emitted in the checked
manifest.  Its lower block is the Construction-A carry realization of the
binary repeated quotient syndrome.  This is only a bounded prerequisite
audit, not a complete SAT-to-CVP reduction or an asymptotic gap claim.
"""

from __future__ import annotations

import argparse
from fractions import Fraction
import hashlib
from itertools import combinations, product
import json
from pathlib import Path

from sympy import Matrix, ZZ
from sympy.matrices.normalforms import smith_normal_form

Q = 2
BOUND2 = 12
PATTERNS = tuple(product((0, 1), repeat=3))
CLAUSES = PATTERNS
N_SELECTORS = len(CLAUSES) * len(PATTERNS)
BASE_ASSIGNMENT = (0, 0, 0)
MANIFEST_PATH = Path(__file__).with_name("gen6_global_selector_manifest.json")


def selector_index(clause, pattern):
    return CLAUSES.index(tuple(clause)) * 8 + PATTERNS.index(tuple(pattern))


def sparse(vector):
    return [[i, int(value)] for i, value in enumerate(vector) if value]


def honest_selector(assignment):
    """One local label per clause, including the uniquely false label."""
    vector = [0] * N_SELECTORS
    for clause in CLAUSES:
        local = tuple(a ^ c for a, c in zip(assignment, clause))
        vector[selector_index(clause, local)] = 1
    return tuple(vector)


def relation_matrix():
    base = honest_selector(BASE_ASSIGNMENT)
    columns = []
    for assignment in PATTERNS[1:]:
        other = honest_selector(assignment)
        columns.append(tuple(x - y for x, y in zip(other, base)))
    return Matrix(N_SELECTORS, len(columns), lambda i, j: columns[j][i])


def fraction_rank(rows):
    """Independent exact rational row reduction (no SymPy rank call)."""
    matrix = [[Fraction(value) for value in row] for row in rows]
    if not matrix:
        return 0
    rank = 0
    columns = len(matrix[0])
    for column in range(columns):
        pivot = next((r for r in range(rank, len(matrix)) if matrix[r][column]), None)
        if pivot is None:
            continue
        matrix[rank], matrix[pivot] = matrix[pivot], matrix[rank]
        scale = matrix[rank][column]
        matrix[rank] = [value / scale for value in matrix[rank]]
        for row in range(len(matrix)):
            if row == rank or not matrix[row][column]:
                continue
            scale = matrix[row][column]
            matrix[row] = [x - scale * y for x, y in zip(matrix[row], matrix[rank])]
        rank += 1
        if rank == len(matrix):
            break
    return rank


def quotient_map(relations):
    """Integral 57-by-64 map with kernel exactly the saturated lattice H."""
    pivot_rows = list(range(7))
    nonpivot_rows = list(range(7, N_SELECTORS))
    pivot = relations[pivot_rows, :]
    assert abs(int(pivot.det())) == 1
    select_pivot = Matrix.eye(N_SELECTORS)[pivot_rows, :]
    select_nonpivot = Matrix.eye(N_SELECTORS)[nonpivot_rows, :]
    projection = select_nonpivot - relations[nonpivot_rows, :] * pivot.inv() * select_pivot
    assert projection * relations == Matrix.zeros(len(nonpivot_rows), relations.cols)
    assert all(value.q == 1 for value in projection)
    return Matrix([[int(value) for value in row] for row in projection.tolist()])


def normalization_checks():
    checks = []
    for clause in CLAUSES:
        vector = [0] * N_SELECTORS
        for pattern in PATTERNS:
            vector[selector_index(clause, pattern)] = 1
        checks.append({"clause": list(clause), "terms": sparse(vector), "rhs_on_deviation": 0})
    return checks


def consistency_checks():
    """Compare each occurrence's global bit marginal with clause 000."""
    checks = []
    reference = CLAUSES[0]
    for clause in CLAUSES[1:]:
        for variable in range(3):
            vector = [0] * N_SELECTORS
            for pattern in PATTERNS:
                vector[selector_index(clause, pattern)] += pattern[variable] ^ clause[variable]
                vector[selector_index(reference, pattern)] -= pattern[variable]
            checks.append({
                "clause": list(clause),
                "reference_clause": list(reference),
                "variable": variable,
                "terms": sparse(vector),
                "rhs_on_deviation": 0,
            })
    return checks


def face_circuits():
    """All square-face selector moves preserving normalization and marginals."""
    circuits = []
    for clause in CLAUSES:
        for first, second in combinations(range(3), 2):
            third = ({0, 1, 2} - {first, second}).pop()
            for fixed in (0, 1):
                vector = [0] * N_SELECTORS
                for left, right, coefficient in ((0, 0, 1), (1, 1, 1),
                                                  (0, 1, -1), (1, 0, -1)):
                    pattern = [0, 0, 0]
                    pattern[first] = left
                    pattern[second] = right
                    pattern[third] = fixed
                    vector[selector_index(clause, pattern)] = coefficient
                circuits.append({
                    "clause": list(clause),
                    "varying_variables": [first, second],
                    "fixed_variable": third,
                    "fixed_value": fixed,
                    "terms": sparse(vector),
                })
    return circuits


def build_manifest():
    relations = relation_matrix()
    projection = quotient_map(relations)
    parity = [[int(value) % Q for value in row] for row in projection.tolist()]
    encoded = parity + parity  # binary [114,57] repeated systematic image
    base = honest_selector(BASE_ASSIGNMENT)

    coordinates = []
    for clause in CLAUSES:
        for pattern in PATTERNS:
            coordinates.append({
                "index": selector_index(clause, pattern),
                "kind": "selector",
                "clause": list(clause),
                "local_pattern": list(pattern),
                "global_assignment_if_one_hot": [p ^ c for p, c in zip(pattern, clause)],
                "legal_for_clause": pattern != (0, 0, 0),
            })

    quotient_relations = []
    for column, assignment in enumerate(PATTERNS[1:]):
        quotient_relations.append({
            "kind": "completeness_difference",
            "assignment": list(assignment),
            "base_assignment": list(BASE_ASSIGNMENT),
            "terms": sparse([int(relations[row, column]) for row in range(N_SELECTORS)]),
        })

    legality = [{
        "clause": list(clause),
        "selector_index": selector_index(clause, (0, 0, 0)),
        "required_selector_value": 0,
    } for clause in CLAUSES]

    syndrome_rows = [{"index": i, "terms": sparse(row)} for i, row in enumerate(parity)]

    # B = [[S, 0], [E S, 2 I]], where S scales each illegal selector by 2.
    # The target is [h_0, E h_0].  Sparse columns emit every basis entry.
    lower_dimension = len(encoded)
    basis_columns = []
    for column in range(N_SELECTORS):
        scale = Q if PATTERNS[column % 8] == (0, 0, 0) else 1
        entries = [[column, scale]]
        for row, encoded_row in enumerate(encoded):
            value = scale * encoded_row[column]
            if value:
                entries.append([N_SELECTORS + row, value])
        basis_columns.append({"index": column, "kind": "selector", "entries": entries})
    for row in range(lower_dimension):
        basis_columns.append({
            "index": N_SELECTORS + row,
            "kind": "construction_a_carry",
            "entries": [[N_SELECTORS + row, Q]],
        })

    target = list(base)
    target.extend(sum(encoded_row[i] * base[i] for i in range(N_SELECTORS))
                  for encoded_row in encoded)
    basis_payload = {"basis_columns": basis_columns, "target": sparse(target)}
    basis_hash = hashlib.sha256(
        json.dumps(basis_payload, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()

    return {
        "schema": "gen6-global-selector-quotient-v1",
        "finite_instance": "all eight clauses on three variables",
        "ambient_module": "Z^64",
        "coordinates": coordinates,
        "slack_coordinates": [],
        "auxiliary_coordinates": [],
        "affine_checks": {
            "normalization": normalization_checks(),
            "variable_consistency": consistency_checks(),
            "legality": legality,
        },
        "quotient": {
            "definition": "Z^64 modulo the seven complete-Boolean assignment differences",
            "relations": quotient_relations,
            "snf_nonzero_diagonal": [1] * 7,
            "free_rank": 57,
            "torsion_invariants": [],
            "integral_syndrome_rows": syndrome_rows,
        },
        "selector_attack_generators": face_circuits(),
        "slack_relations": [],
        "auxiliary_relations": [],
        "construction_a_audit": {
            "modulus": Q,
            "outer_code": "binary repetition s -> (s,s) on the 57 quotient coordinates",
            "dimension": N_SELECTORS + lower_dimension,
            "basis_columns": basis_columns,
            "target": sparse(target),
            "determinant_absolute": str(Q ** (8 + lower_dimension)),
            "basis_target_sha256": basis_hash,
        },
    }


def local_candidates(false_value):
    """All local normalized moves of norm <=12 with prescribed 000 entry."""
    by_literal_delta = {}
    for rest in product(range(-3, 4), repeat=7):
        vector = (false_value,) + rest
        norm2 = sum(value * value for value in vector)
        if norm2 > BOUND2 or sum(vector) != 0:
            continue
        delta = tuple(sum(vector[i] * PATTERNS[i][j] for i in range(8))
                      for j in range(3))
        by_literal_delta.setdefault(delta, []).append((norm2, vector))
    for records in by_literal_delta.values():
        records.sort()
    return by_literal_delta


def global_delta_to_literal(clause, global_delta):
    # For a normalized deviation, complementing an occurrence negates its delta.
    return tuple(-value if clause[j] else value for j, value in enumerate(global_delta))


def fast_quotient_coordinates(vector):
    """Coordinates from the unimodular pivot used by quotient_map()."""
    # In clause 000, rows 000..110 are a unimodular 7-row pivot.
    # Relations 001..110 have their +1 on the matching row; relation 111
    # is recovered from the common -1 on row 000.
    coefficients = list(vector[1:7])
    coefficients.append(-vector[0] - sum(vector[1:7]))
    total = sum(coefficients)
    quotient = []
    for index in range(7, N_SELECTORS):
        clause = CLAUSES[index // 8]
        pattern = PATTERNS[index % 8]
        if pattern == clause:
            relation_value = -total
        else:
            assignment = tuple(p ^ c for p, c in zip(pattern, clause))
            relation_value = coefficients[PATTERNS.index(assignment) - 1]
        quotient.append(vector[index] - relation_value)
    return tuple(quotient)


def check_manifest(manifest, relations, projection):
    rebuilt = build_manifest()
    assert manifest == rebuilt
    assert len(manifest["coordinates"]) == 64
    assert len(manifest["affine_checks"]["normalization"]) == 8
    assert len(manifest["affine_checks"]["variable_consistency"]) == 21
    assert len(manifest["quotient"]["relations"]) == 7
    assert len(manifest["selector_attack_generators"]) == 48
    assert manifest["slack_coordinates"] == manifest["auxiliary_coordinates"] == []

    diagonal = smith_normal_form(relations, domain=ZZ)
    invariants = [abs(int(diagonal[i, i])) for i in range(min(diagonal.shape))
                  if diagonal[i, i]]
    assert invariants == [1] * 7
    independent_rank = fraction_rank(relations.T.tolist())
    assert independent_rank == 7
    assert projection.shape == (57, 64)
    assert fraction_rank(projection.tolist()) == 57

    construction = manifest["construction_a_audit"]
    assert construction["dimension"] == 178
    assert len(construction["basis_columns"]) == 178
    assert int(construction["determinant_absolute"]) == Q ** 122
    occupied_pivots = []
    for column in construction["basis_columns"]:
        entries = dict(column["entries"])
        pivot = column["index"]
        assert pivot in entries and entries[pivot] in (1, Q)
        assert all(row >= pivot or row >= N_SELECTORS for row in entries)
        occupied_pivots.append(pivot)
    assert occupied_pivots == list(range(178))
    return invariants, independent_rank


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write-manifest", action="store_true")
    args = parser.parse_args()

    expected_manifest = build_manifest()
    if args.write_manifest:
        MANIFEST_PATH.write_text(json.dumps(expected_manifest, indent=2, sort_keys=True) + "\n")
        print(MANIFEST_PATH)
        return

    manifest = json.loads(MANIFEST_PATH.read_text())
    relations = relation_matrix()
    projection = quotient_map(relations)
    invariants, independent_rank = check_manifest(manifest, relations, projection)

    false_local = local_candidates(-1)
    legal_local = local_candidates(0)
    base_vectors = [honest_selector(assignment) for assignment in PATTERNS]

    harmful_checked = 0
    exact_zero_count = 0
    modular_zero_count = 0
    minimum_norm2 = None
    minimum_audit_distance2 = None
    minimum_syndrome_weight = None
    first_harmful = None
    feasible_global_deltas = set()

    for base_index, base_assignment in enumerate(PATTERNS):
        possible_global_deltas = {
            tuple(-value if base_assignment[j] else value for j, value in enumerate(local_delta))
            for local_delta in false_local
        }
        budget_feasible = []
        for global_delta in possible_global_deltas:
            minimum_total = 0
            choices_by_clause = []
            possible = True
            for clause_index, clause in enumerate(CLAUSES):
                table = false_local if clause_index == base_index else legal_local
                choices = table.get(global_delta_to_literal(clause, global_delta))
                if not choices:
                    possible = False
                    break
                minimum_total += choices[0][0]
                choices_by_clause.append(choices)
            if possible and minimum_total <= BOUND2:
                budget_feasible.append((global_delta, choices_by_clause))
                feasible_global_deltas.add(global_delta)

        # Exact minimization over all local candidates proves that no common
        # marginal shift other than zero enters the requested norm ball.
        assert [delta for delta, _ in budget_feasible] == [(0, 0, 0)]

        for global_delta, choices_by_clause in budget_feasible:
            blocks = [None] * 8

            def recurse(clause_index, remaining):
                nonlocal harmful_checked, exact_zero_count, modular_zero_count
                nonlocal minimum_norm2, minimum_audit_distance2
                nonlocal minimum_syndrome_weight, first_harmful
                if clause_index == 8:
                    deviation = tuple(value for block in blocks for value in block)
                    norm2 = sum(value * value for value in deviation)
                    exact = fast_quotient_coordinates(deviation)
                    mod_two = tuple(value % Q for value in exact)
                    exact_zero = not any(exact)
                    modular_zero = not any(mod_two)
                    harmful_checked += 1
                    exact_zero_count += int(exact_zero)
                    modular_zero_count += int(modular_zero)
                    syndrome_weight = sum(mod_two)
                    audit_distance2 = norm2 + 2 * syndrome_weight
                    minimum_norm2 = norm2 if minimum_norm2 is None else min(minimum_norm2, norm2)
                    minimum_syndrome_weight = (syndrome_weight if minimum_syndrome_weight is None
                                               else min(minimum_syndrome_weight, syndrome_weight))
                    minimum_audit_distance2 = (audit_distance2 if minimum_audit_distance2 is None
                                               else min(minimum_audit_distance2, audit_distance2))

                    # Independently check every emitted affine condition.
                    moved = tuple(x + y for x, y in zip(base_vectors[base_index], deviation))
                    assert all(sum(moved[selector_index(clause, pattern)]
                                   for pattern in PATTERNS) == 1 for clause in CLAUSES)
                    for clause in CLAUSES:
                        assert moved[selector_index(clause, (0, 0, 0))] == 0
                    marginals = []
                    for clause in CLAUSES:
                        marginals.append(tuple(
                            sum((pattern[j] ^ clause[j]) * moved[selector_index(clause, pattern)]
                                for pattern in PATTERNS) for j in range(3)))
                    assert len(set(marginals)) == 1
                    assert marginals[0] == tuple(base_assignment[j] + global_delta[j]
                                                  for j in range(3))
                    if first_harmful is None:
                        # Cross-check the optimized quotient coordinates once
                        # against the emitted 57-by-64 integral projection.
                        slow = tuple(sum(int(projection[row, column]) * deviation[column]
                                         for column in range(N_SELECTORS))
                                     for row in range(projection.rows))
                        assert slow == exact
                        first_harmful = {
                            "base_assignment": list(base_assignment),
                            "global_marginal_delta": list(global_delta),
                            "deviation": list(deviation),
                            "squared_norm": norm2,
                            "quotient_syndrome": list(exact),
                            "binary_syndrome_weight": syndrome_weight,
                            "construction_a_audit_squared_distance": audit_distance2,
                        }
                    return

                for norm2, vector in choices_by_clause[clause_index]:
                    if norm2 > remaining:
                        break
                    blocks[clause_index] = vector
                    recurse(clause_index + 1, remaining - norm2)

            recurse(0, BOUND2)

    assert feasible_global_deltas == {(0, 0, 0)}
    assert harmful_checked == 156880
    assert exact_zero_count == 0
    assert modular_zero_count == 0
    assert minimum_norm2 == 4
    assert minimum_syndrome_weight is not None and minimum_syndrome_weight > 0

    manifest_hash = hashlib.sha256(
        json.dumps(manifest, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()
    print(json.dumps({
        "manifest": str(MANIFEST_PATH.relative_to(MANIFEST_PATH.parents[1])),
        "manifest_sha256": manifest_hash,
        "selector_coordinates": 64,
        "slack_coordinates": 0,
        "auxiliary_coordinates": 0,
        "normalization_checks": 8,
        "variable_consistency_checks": 21,
        "completeness_difference_relations": 7,
        "quotient_snf_nonzero_diagonal": invariants,
        "quotient_free_rank": 57,
        "independent_rational_relation_rank": independent_rank,
        "harmful_deviations_checked": harmful_checked,
        "squared_norm_bound": BOUND2,
        "feasible_global_marginal_deltas": [list(value) for value in sorted(feasible_global_deltas)],
        "minimum_harmful_squared_norm": minimum_norm2,
        "exact_zero_quotient_syndromes": exact_zero_count,
        "binary_modular_bypasses": modular_zero_count,
        "minimum_binary_syndrome_weight": minimum_syndrome_weight,
        "minimum_construction_a_audit_squared_distance": minimum_audit_distance2,
        "construction_a_basis_dimension": 178,
        "construction_a_basis_determinant_absolute": str(Q ** 122),
        "first_harmful": first_harmful,
        "finding": "no harmful deviation of squared norm at most 12 vanishes in the honest-difference quotient or modulo 2; finite prerequisite survival only",
    }, sort_keys=True))


if __name__ == "__main__":
    main()
