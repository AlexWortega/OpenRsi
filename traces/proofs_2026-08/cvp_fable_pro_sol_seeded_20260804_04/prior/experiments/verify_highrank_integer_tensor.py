"""Hostile mutation: higher-rank homogenized integer 3DM tensor search.

Construct an exact Z-basis of L={(z,s):Az=s1} from a rational nullspace,
saturate by column Hermite normal form, then attack L⊗L with exact bounded
mixed coefficient search.  Instances are selected for homogeneous rank 3 or 4,
where genuine mixed combinations exist.  Pure products supply an upper bound;
any smaller vector is a certified mixed-tensor collapse.
"""
from __future__ import annotations
import itertools,random
