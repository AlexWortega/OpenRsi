 # rank 3 => tensor rank 9, exhaustive 3^9; rank 4 => 3^16=43m too large,
 # use structured support<=3 search below.
 for yes in [True,False]:
  for T,B in sample(q,9,3,yes,6):cases.append(('Y' if yes else 'N',T,B))
