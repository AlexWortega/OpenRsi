#!/usr/bin/env python3
"""Finite all-sublattice diagnostics for homogenized integer 3DM lattices.

For rank-3 exact Z-bases found in verify_highrank_integer_tensor, enumerate all
primitive rank-1/2 sublattices generated by coefficient vectors in {-1,0,1}.
Record Gram determinants, ambient coordinate support, and whether NO instances
show a uniform determinant/support advantage over YES.  Every finite count is
asserted; this is construction diagnostics toward a Haviv--Regev-type lemma.
"""
from __future__ import annotations
import itertools,math
from fractions import Fraction
import verify_highrank_integer_tensor as ht


def dot(x,y):return sum(a*b for a,b in zip(x,y))
def det2(u,v):return dot(u,u)*dot(v,v)-dot(u,v)**2
def vec(B,c):return tuple(sum(c[i]*B[i][j] for i in range(len(B))) for j in range(len(B[0])))
def primitive(c):
 g=0
 for a in c:g=math.gcd(g,abs(a))
 return tuple(a//g for a in c) if g else c
def canon_sign(c):
 c=primitive(c)
 for a in c:
  if a:return tuple(-x for x in c) if a<0 else c
 return c
def rank2(c,d):return any(c[i]*d[j]!=c[j]*d[i] for i in range(len(c)) for j in range(i+1,len(c)))
def coeff_vectors(r):return sorted({canon_sign(c) for c in itertools.product((-1,0,1),repeat=r) if any(c)})
def support(vs):return sum(any(v[j] for v in vs) for j in range(len(vs[0])))
def analyze(B):
 C=coeff_vectors(len(B)); V={c:vec(B,c) for c in C}
 rank1=[(dot(V[c],V[c]),support([V[c]]),c) for c in C]
 rank2s=[]
 for i,c in enumerate(C):
  for d in C[i+1:]:
   if rank2(c,d):rank2s.append((det2(V[c],V[d]),support([V[c],V[d]]),c,d))
 return min(rank1),min(rank2s),len(C),len(rank2s),sorted(set(x[0] for x in rank2s))[:10]
def main():
 q=3; rec=[]
 for yes in [True,False]:
  fam=ht.sample(q,9,3,yes,12)
  assert len(fam)==12
  for T,B in fam:
   a=analyze(B);rec.append(('Y' if yes else 'N',a,T))
 for x in rec:print(x[0],x[1])
 Y=[x[1] for x in rec if x[0]=='Y'];N=[x[1] for x in rec if x[0]=='N']
 summary={'Y_min_rank1_norm':min(x[0][0] for x in Y),
  'N_min_rank1_norm':min(x[0][0] for x in N),
  'Y_min_rank2_gramdet':min(x[1][0] for x in Y),
  'N_min_rank2_gramdet':min(x[1][0] for x in N),
  'Y_min_rank2_support':min(x[1][1] for x in Y),
  'N_min_rank2_support':min(x[1][1] for x in N),
  'instances_each':12}
 print(summary)
 assert all(x[2]==13 and x[3]==78 for x in Y+N)
 # Honest finite outcome: NO lattices have short s=0 directions and rank-two
 # sublattices matching YES determinant/support, so a naive unrestricted
 # all-sublattices gap is false even though pointed tensor minima survived.
 assert summary=={'Y_min_rank1_norm':4,'N_min_rank1_norm':4,
  'Y_min_rank2_gramdet':12,'N_min_rank2_gramdet':12,
  'Y_min_rank2_support':6,'N_min_rank2_support':6,'instances_each':12}
 print('tensor sublattice determinant diagnostics pass')
if __name__=='__main__':main()
