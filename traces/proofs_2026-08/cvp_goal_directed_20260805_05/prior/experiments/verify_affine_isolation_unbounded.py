#!/usr/bin/env python3
"""Exact unbounded audit of all 18 Generation-2 boxed survivors.

For a fixed legal one-hot selector e_i, a harmful configuration z obeys
A z = b_i, where rows of A are selector normalization, three marginals,
and three degree-one measurement rows. The first seven columns are the
satisfying OR-pattern selectors and the last five are auxiliaries.

The 18 survivors are generated by row permutations of one selector-row
map and by placing all five auxiliaries on one row. For each survivor and
each i, this verifier constructs an integral left-kernel certificate w:

    w^T A = 0, but w^T b_i != 0.

This proves the affine fiber empty over Q and hence over all integers,
without a coefficient box or a closest-vector search. The implementation
also performs exact rational Gaussian elimination independently.

This is a local finite certificate. It gives no overlap, scaling, or CVP
hardness theorem.
"""

from fractions import Fraction
from itertools import permutations, product
import json

PATTERNS = tuple(p for p in product((0, 1), repeat=3) if p != (0, 0, 0))
BASE_SELECTOR_ROWS = (0, 0, 1, 0, 1, 1, 2)
AUX_COLUMNS = 5


def relabel(values, permutation):
    return tuple(permutation[value] for value in values)


def build_matrix(selector_rows, auxiliary_rows):
    rows = []
    rows.append([1] * 7 + [0] * AUX_COLUMNS)
    for marginal in range(3):
        rows.append([p[marginal] for p in PATTERNS] + [0] * AUX_COLUMNS)
    for measurement_row in range(3):
        rows.append(
            [int(row == measurement_row) for row in selector_rows]
            + [int(row == measurement_row) for row in auxiliary_rows]
        )
    return tuple(tuple(row) for row in rows)


def rhs(selector_rows, legal_index):
    return (1, 0, 0, 0) + tuple(
        int(selector_rows[legal_index] == row) for row in range(3)
    )


def dot(left, right):
    return sum(x * y for x, y in zip(left, right))


def rational_consistent(matrix, target):
    augmented = [list(map(Fraction, row)) + [Fraction(value)]
                 for row, value in zip(matrix, target)]
    pivot_row = 0
    columns = len(matrix[0])
    for column in range(columns):
        pivot = next((row for row in range(pivot_row, len(augmented))
                      if augmented[row][column]), None)
        if pivot is None:
            continue
        augmented[pivot_row], augmented[pivot] = augmented[pivot], augmented[pivot_row]
        scale = augmented[pivot_row][column]
        augmented[pivot_row] = [value / scale for value in augmented[pivot_row]]
        for row in range(len(augmented)):
            if row == pivot_row or not augmented[row][column]:
                continue
            scale = augmented[row][column]
            augmented[row] = [x - scale * y for x, y in
                              zip(augmented[row], augmented[pivot_row])]
        pivot_row += 1
    return not any(
        all(value == 0 for value in row[:columns]) and row[columns] != 0
        for row in augmented
    )


def main():
    # Reconstruct and certify the exact 18 matrices listed by Generation 2.
    survivors = []
    certificates_checked = 0
    pairings = []
    seen = set()
    for selector_permutation in permutations(range(3)):
        selector_rows = relabel(BASE_SELECTOR_ROWS, selector_permutation)
        # Solve the tiny integer left kernel by bounded exact enumeration.
        matrix_without_aux = build_matrix(selector_rows, (0,) * AUX_COLUMNS)
        for auxiliary_host in range(3):
            auxiliary_rows = (auxiliary_host,) * AUX_COLUMNS
            matrix = build_matrix(selector_rows, auxiliary_rows)
            certificate = None
            for candidate in product(range(-3, 4), repeat=7):
                if candidate == (0,) * 7:
                    continue
                if all(sum(candidate[row] * matrix[row][column]
                           for row in range(7)) == 0 for column in range(12)):
                    certificate = candidate
                    break
            if certificate is None:
                continue
            key = (selector_rows, auxiliary_rows)
            if key in seen:
                continue
            targets = [rhs(selector_rows, i) for i in range(7)]
            target_pairings = [dot(certificate, target) for target in targets]
            if not all(target_pairings):
                continue
            seen.add(key)
            for target, target_pairing in zip(targets, target_pairings):
                assert target_pairing != 0
                assert not rational_consistent(matrix, target)
                certificates_checked += 1
                pairings.append(abs(target_pairing))
            survivors.append({
                "selector_column_rows": list(selector_rows),
                "auxiliary_column_rows": list(auxiliary_rows),
                "left_kernel_certificate": list(certificate),
                "certificate_rhs_pairings_by_legal_index": target_pairings,
            })

    assert len(survivors) == 18
    assert certificates_checked == 18 * 7
    assert min(pairings) >= 1

    print(json.dumps({
        "survivors_certified": len(survivors),
        "legal_targets_certified_infeasible": certificates_checked,
        "minimum_absolute_certificate_pairing": min(pairings),
        "maximum_absolute_certificate_pairing": max(pairings),
        "field": "Q (therefore also Z)",
        "survivors": survivors,
        "finding": "all 18 boxed survivors have empty unbounded harmful affine fibers"
    }, sort_keys=True))


if __name__ == "__main__":
    main()
