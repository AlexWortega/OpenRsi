#!/usr/bin/env python3
"""Finite exhaustive checks of the fractional-cylinder packing lemma.

For K2 states, enumerate every family of r=2 partial assignments over m=4
and verify max size 4=2^r. For C5, verify saved exact clique certificates for
m=3,4,5,r=2 have size 5 <= (5/2)^2, including pairwise separation.
"""
import itertools,json,os
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def objs(m,r,q):
 for B in itertools.combinations(range(m),r):
  for a in itertools.product(range(q),repeat=r):yield dict(zip(B,a))
def sep(a,b,H):return any((a[x],b[x]) in H for x in a.keys()&b.keys())
# Exact maximum clique by brute force over 24 objects, using branch and bound.
O=list(objs(4,2,2)); H2={(0,1),(1,0)}; adj=[]
for i,a in enumerate(O):adj.append(sum((1<<j) for j,b in enumerate(O) if j!=i and sep(a,b,H2)))
best=0
def expand(P,n):
 global best
 if n+P.bit_count()<=best:return
 if not P:best=max(best,n);return
 while P and n+P.bit_count()>best:
  lb=P&-P;v=lb.bit_length()-1;P-=lb;expand(P&adj[v],n+1)
expand((1<<len(O))-1,0);assert best==4
# Validate exact C5 certificates generated by networkx maximum-clique enumeration.
H5={(i,(i+1)%5) for i in range(5)}|{((i+1)%5,i) for i in range(5)}
for m in (3,4,5):
 d=json.load(open(os.path.join(ROOT,f'experiments/results/partial_c5_m{m}_r2.json')))
 assert d['max']==5 and 5 <= (5/2)**2
 fam=[dict((int(x),int(y)) for x,y in f) for f in d['family']]
 assert all(sep(a,b,H5) for a,b in itertools.combinations(fam,2))
print('PASS: exact K2 m=4,r=2 maximum 4; C5 saved families pairwise separated and obey 5 <= chi_f(C5)^2=6.25')
